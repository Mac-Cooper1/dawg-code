/**
 * The conversation as the engine holds it. See docs/specs/phase-2-engine-core.md.
 *
 * History is append-only: a message is never edited after it is added (only compaction replaces
 * history). Everything here must serialise the same way every time, because the prompt cache
 * depends on each request repeating the previous one byte for byte.
 */
import type { ContentPart } from "@dawg/protocol";

export interface SystemMessage {
  role: "system";
  content: string;
}

export interface UserMessage {
  role: "user";
  content: ContentPart[];
  /**
   * "prompt" is something the person typed. "note" is a system note the engine appended (the date
   * rolled over, a file changed, a background command finished). Notes use the user role because
   * many chat templates accept a system message only at the very start.
   */
  kind: "prompt" | "note";
}

export interface ToolCall {
  /** Unique within the session. Generated by the engine when the model gives none. */
  id: string;
  name: string;
  /**
   * JSON text of an object. It always parses: when the model's output had to be repaired, this is
   * the repaired text, and when it could not be repaired this is "{}".
   */
  arguments: string;
  /**
   * What the model actually produced, kept only when it had to be repaired, coerced or thrown
   * away. A difference in spacing alone does not count. Never sent back to the model.
   */
  rawArguments?: string;
}

export interface AssistantMessage {
  role: "assistant";
  content: string;
  /** Reasoning text, kept because current model cards require it to be sent back. */
  reasoning?: string;
  toolCalls: ToolCall[];
}

export interface ToolResultMessage {
  role: "tool";
  toolCallId: string;
  toolName: string;
  content: ContentPart[];
  isError: boolean;
}

export type Message = SystemMessage | UserMessage | AssistantMessage | ToolResultMessage;
