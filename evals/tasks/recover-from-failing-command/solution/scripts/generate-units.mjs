// Turns data/units.csv into src/generated/units.js.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const csv = readFileSync(join(root, "data", "units.csv"), "utf8");

const [header, ...rows] = csv.trim().split("\n");
const columns = header.split(",");
const units = rows.map((line, i) => {
  const cells = line.split(",");
  if (cells.length !== columns.length) {
    throw new Error(`units.csv line ${i + 2}: expected ${columns.length} columns, got ${cells.length}`);
  }
  const unit = Object.fromEntries(columns.map((c, j) => [c, cells[j].trim()]));
  unit.factor = Number(unit.factor);
  if (!(unit.factor > 0)) throw new Error(`units.csv line ${i + 2}: bad factor`);
  return unit;
});

// src/generated/ is git-ignored, so it does not exist in a fresh clone.
mkdirSync(join(root, "src", "generated"), { recursive: true });
const out = join(root, "src", "generated", "units.js");
writeFileSync(
  out,
  `// Generated by scripts/generate-units.mjs from data/units.csv. Do not edit.\n` +
    `export const UNITS = Object.freeze(${JSON.stringify(units, null, 2)});\n`,
);
console.log(`wrote ${units.length} units to src/generated/units.js`);
