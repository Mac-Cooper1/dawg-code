/** src/tally/csv_import.py (74 lines). */
export const CSV_IMPORT_PY = [
  '"""Read receipts exported as CSV."""',
  "",
  "import csv",
  "from concurrent.futures import ThreadPoolExecutor, as_completed",
  "from dataclasses import dataclass",
  "from decimal import Decimal, InvalidOperation",
  "from pathlib import Path",
  "",
  "CHUNK_ROWS = 1_000",
  "WORKERS = 4",
  "",
  "",
  "@dataclass(frozen=True)",
  "class CsvRow:",
  "    line: int",
  "    description: str",
  "    amount: Decimal",
  "    currency: str",
  "    paid_by: str",
  "",
  "",
  "class ImportError_(ValueError):",
  "    def __init__(self, line: int, message: str):",
  '        super().__init__(f"line {line}: {message}")',
  "        self.line = line",
  "",
  "",
  "def _parse(line: int, record: dict[str, str]) -> CsvRow:",
  "    try:",
  '        amount = Decimal(record["amount"])',
  "    except InvalidOperation:",
  "        raise ImportError_(line, f\"not an amount: {record['amount']!r}\") from None",
  "    return CsvRow(",
  "        line=line,",
  '        description=record["description"].strip(),',
  "        amount=amount,",
  '        currency=record["currency"].upper(),',
  '        paid_by=record["paid_by"].strip(),',
  "    )",
  "",
  "",
  "def _parse_chunk(chunk: list[tuple[int, dict[str, str]]]) -> list[CsvRow]:",
  "    return [_parse(line, record) for line, record in chunk]",
  "",
  "",
  "def _chunks(path: Path):",
  '    with path.open(newline="") as f:',
  "        reader = csv.DictReader(f)",
  "        chunk = []",
  "        for line, record in enumerate(reader, start=2):",
  "            if not any(record.values()):",
  "                continue",
  "            chunk.append((line, record))",
  "            if len(chunk) == CHUNK_ROWS:",
  "                yield chunk",
  "                chunk = []",
  "        if chunk:",
  "            yield chunk",
  "",
  "",
  "def import_csv(path: Path) -> list[CsvRow]:",
  '    """Parse a receipts CSV, a chunk of rows per worker."""',
  "    rows: list[CsvRow] = []",
  "    with ThreadPoolExecutor(max_workers=WORKERS) as executor:",
  "        futures = [executor.submit(_parse_chunk, c) for c in _chunks(path)]",
  "        for future in as_completed(futures):",
  "            rows.extend(future.result())",
  "    return rows",
  "",
  "",
  "def import_csv_rows(path: Path) -> int:",
  '    """How many rows import_csv would return, without keeping them."""',
  "    return sum(len(c) for c in _chunks(path))",
  "",
];

/** src/tally/bill.py (88 lines). */
export const BILL_PY = [
  '"""Split a bill between the people at the table."""',
  "",
  "from collections import defaultdict",
  "from dataclasses import dataclass, field",
  "from decimal import Decimal",
  "",
  "from tally.money import CENT, split_evenly, sum_amounts, to_cents",
  "",
  "",
  "@dataclass(frozen=True)",
  "class Item:",
  "    description: str",
  "    amount: Decimal",
  "    ordered_by: tuple[str, ...]",
  "",
  "",
  "@dataclass",
  "class Bill:",
  "    items: list[Item] = field(default_factory=list)",
  "    people: list[str] = field(default_factory=list)",
  "",
  "    def add(self, description: str, amount: Decimal, *ordered_by: str) -> None:",
  "        if not ordered_by:",
  '            raise ValueError(f"nobody ordered {description!r}")',
  "        for person in ordered_by:",
  "            if person not in self.people:",
  "                self.people.append(person)",
  "        self.items.append(Item(description, to_cents(amount), tuple(ordered_by)))",
  "",
  "    def subtotal(self) -> Decimal:",
  "        return sum_amounts([item.amount for item in self.items])",
  "",
  "",
  "def split_bill(bill: Bill, *, shared: bool = False) -> dict[str, Decimal]:",
  '    """What each person owes.',
  "",
  "    shared=True splits the whole bill evenly. Otherwise each item is split between the",
  "    people who ordered it, and the leftover cents go to whoever ordered first.",
  '    """',
  "    if not bill.people:",
  "        return {}",
  "    if shared:",
  "        shares = split_evenly(bill.subtotal(), len(bill.people))",
  "        return dict(zip(bill.people, shares))",
  "",
  "    owed: dict[str, Decimal] = defaultdict(Decimal)",
  "    for item in bill.items:",
  "        parts = split_evenly(item.amount, len(item.ordered_by))",
  "        for person, part in zip(item.ordered_by, parts):",
  "            owed[person] += part",
  "    return {person: to_cents(owed[person]) for person in bill.people}",
  "",
  "",
  "def settle_up(owed: dict[str, Decimal], paid: dict[str, Decimal]) -> list[tuple[str, str, Decimal]]:",
  '    """Who pays whom, fewest transfers first."""',
  "    balance = {p: paid.get(p, Decimal(0)) - owed.get(p, Decimal(0)) for p in owed | paid}",
  "    debtors = sorted((p for p in balance if balance[p] < 0), key=lambda p: balance[p])",
  "    creditors = sorted((p for p in balance if balance[p] > 0), key=lambda p: -balance[p])",
  "    transfers = []",
  "    while debtors and creditors:",
  "        debtor, creditor = debtors[0], creditors[0]",
  "        amount = min(-balance[debtor], balance[creditor])",
  "        if amount < CENT:",
  "            break",
  "        transfers.append((debtor, creditor, amount))",
  "        balance[debtor] += amount",
  "        balance[creditor] -= amount",
  "        if balance[debtor] >= 0:",
  "            debtors.pop(0)",
  "        if balance[creditor] <= 0:",
  "            creditors.pop(0)",
  "    return transfers",
  "",
  "",
  "def describe(owed: dict[str, Decimal]) -> str:",
  '    """One line per person, for the receipt footer."""',
  "    width = max((len(p) for p in owed), default=0)",
  '    return "\\n".join(f"{p.ljust(width)}  {amount:>8}" for p, amount in owed.items())',
  "",
  "",
  "def people_who_ordered(bill: Bill, description: str) -> tuple[str, ...]:",
  "    for item in bill.items:",
  "        if item.description == description:",
  "            return item.ordered_by",
  "    raise KeyError(description)",
  "",
  "",
  '__all__ = ["Bill", "Item", "split_bill", "settle_up", "describe"]',
];

