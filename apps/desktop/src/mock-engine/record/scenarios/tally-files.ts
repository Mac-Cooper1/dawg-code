  "from decimal import Decimal, ROUND_HALF_UP",
  "",
  'CENT = Decimal("0.01")',
  "",
  "",
  "def to_cents(amount: Decimal) -> Decimal:",
  "    return amount.quantize(CENT, rounding=ROUND_HALF_UP)",
  "",
  "",
  "def split_evenly(total: Decimal, parts: int) -> list[Decimal]:",
  '    """Split total into parts that add up to it exactly."""',
  "    if parts < 1:",
  '        raise ValueError("parts must be at least 1")',
  "    share = (total / parts).quantize(CENT, rounding=ROUND_HALF_UP)",
  "    return [share] * parts",
  "",
  "",
  'def format_amount(amount: Decimal, currency: str = "USD") -> str:',
  '    """Format an amount for a receipt line, for example "$1,234.50"."""',
  '    symbol = SYMBOLS.get(currency, currency + " ")',
  '    sign = "-" if amount < 0 else ""',
  '    return f"{sign}{symbol}{abs(to_cents(amount)):,.2f}"',
  "",
  "",
  "def parse_amount(text: str) -> Decimal:",
  '    """Read an amount a person typed: "12", "12.5", "$12.50", "1,200.00"."""',
  '    cleaned = text.strip().lstrip("$").replace(",", "")',
  "    if not cleaned:",
  '        raise ValueError("empty amount")',
  "    return to_cents(Decimal(cleaned))",
  "",
  "",
  "def sum_amounts(amounts: list[Decimal]) -> Decimal:",
  '    return to_cents(sum(amounts, Decimal("0")))',
  "",
  "",
  "SYMBOLS = {",
  '    "USD": "$",',
  '    "EUR": "€",',
  '    "GBP": "£",',
  '    "JPY": "¥",',
