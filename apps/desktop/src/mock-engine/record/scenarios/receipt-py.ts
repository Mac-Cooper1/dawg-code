export const RECEIPT_PY = [
  '"""Receipts: lines, payers and totals."""',
  "",
  "from __future__ import annotations",
  "",
  "from dataclasses import dataclass, field",
  "from datetime import date",
  "from decimal import Decimal",
  "",
  "from tally.money import format_amount, split_evenly, sum_amounts, to_cents",
  "",
  "",
  "@dataclass(frozen=True)",
  "class Line:",
  "    description: str",
  "    amount: Decimal",
  '    currency: str = "USD"',
  "    quantity: int = 1",
  "",
  "    @property",
  "    def total(self) -> Decimal:",
  "        return to_cents(self.amount * self.quantity)",
  "",
  "",
  "@dataclass",
  "class Receipt:",
  "    merchant: str",
  "    day: date",
  '    currency: str = "USD"',
  "    lines: list[Line] = field(default_factory=list)",
  "    payers: list[str] = field(default_factory=list)",
  "    tax_rate: Decimal = Decimal(0)",
  "",
  "    def add_line(",
  "        self,",
  "        description: str,",
  "        amount: Decimal,",
  "        *,",
  "        quantity: int = 1,",
  "        currency: str | None = None,",
  "    ) -> Line:",
  "        line = Line(description, to_cents(amount), currency or self.currency, quantity)",
  "        self.lines.append(line)",
  "        return line",
  "",
  "    def add_payer(self, name: str) -> None:",
  "        if name in self.payers:",
  '            raise ValueError(f"{name} is already paying")',
  "        self.payers.append(name)",
  "",
  "    def subtotal(self) -> Decimal:",
  "        # Every line is assumed to be in the receipt's currency.",
  "        return sum_amounts([line.total for line in self.lines])",
  "",
  "    def tax(self) -> Decimal:",
  "        return to_cents(self.subtotal() * self.tax_rate)",
  "",
  "    def total(self) -> Decimal:",
  "        return to_cents(self.subtotal() + self.tax())",
  "",
  "    def shares(self) -> dict[str, Decimal]:",
  "        if not self.payers:",
  '            raise ValueError("a receipt needs at least one payer")',
  "        return dict(zip(self.payers, split_evenly(self.total(), len(self.payers))))",
  "",
  "    def currencies(self) -> set[str]:",
  "        return {line.currency for line in self.lines}",
  "",
  "    def is_mixed(self) -> bool:",
  "        return len(self.currencies() - {self.currency}) > 0",
  "",
  "    def describe(self) -> str:",
  '        """The receipt as plain text, for the terminal and the email summary."""',
  "        width = max((len(line.description) for line in self.lines), default=10)",
  '        rows = [f"{self.merchant}  {self.day.isoformat()}"]',
  "        for line in self.lines:",
  '            qty = f" x{line.quantity}" if line.quantity > 1 else ""',
  "            amount = format_amount(line.total, line.currency)",
  '            rows.append(f"  {(line.description + qty).ljust(width + 4)} {amount:>12}")',
  '        rows.append(f"  {"Subtotal".ljust(width + 4)} {format_amount(self.subtotal(), self.currency):>12}")',
  "        if self.tax_rate:",
  '            rows.append(f"  {"Tax".ljust(width + 4)} {format_amount(self.tax(), self.currency):>12}")',
  '        rows.append(f"  {"Total".ljust(width + 4)} {format_amount(self.total(), self.currency):>12}")',
  '        return "\\n".join(rows)',
  "",
  "",
  "def merge(first: Receipt, second: Receipt) -> Receipt:",
  "    if (first.merchant, first.day) != (second.merchant, second.day):",
  '        raise ValueError("only receipts from the same visit can be merged")',
  "    if first.currency != second.currency:",
  '        raise ValueError("receipts in different currencies cannot be merged")',
  "    merged = Receipt(first.merchant, first.day, first.currency, tax_rate=first.tax_rate)",
  "    merged.lines = [*first.lines, *second.lines]",
  "    merged.payers = list(dict.fromkeys([*first.payers, *second.payers]))",
  "    return merged",
  "",
  "",
  "def from_rows(rows: list[dict[str, str]], *, merchant: str, day: date) -> Receipt:",
  '    """A receipt from CSV rows (see csv_import)."""',
  "    receipt = Receipt(merchant, day)",
  "    for row in rows:",
  "        receipt.add_line(",
  '            row["description"],',
  '            Decimal(row["amount"]),',
  '            quantity=int(row.get("quantity") or 1),',
  '            currency=row.get("currency") or None,',
  "        )",
  '        payer = row.get("paid_by")',
  "        if payer and payer not in receipt.payers:",
  "            receipt.add_payer(payer)",
  "    return receipt",
  "",
  "",
  "def totals_by_currency(receipts: list[Receipt]) -> dict[str, Decimal]:",
  "    out: dict[str, Decimal] = {}",
  "    for receipt in receipts:",
  "        out[receipt.currency] = to_cents(out.get(receipt.currency, Decimal(0)) + receipt.total())",
  "    return out",
  "",
  "",
  "def largest_line(receipt: Receipt) -> Line | None:",
  "    return max(receipt.lines, key=lambda line: line.total, default=None)",
  "",
  "",
  "__all__ = [",
  '    "Line",',
  '    "Receipt",',
  '    "from_rows",',
  '    "largest_line",',
  '    "merge",',
  '    "totals_by_currency",',
  "]",
];
